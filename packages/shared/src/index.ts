// Event contract shared by every app. Mirrors section 5 of the root README.

export * from "./api.js";

export const EXAM_EVENT_TYPES = [
  "SESSION_STARTED",
  "SESSION_ENDED",
  "TAB_ACTIVATED",
  "TAB_CREATED",
  "EXAM_TAB_HIDDEN",
  "EXAM_TAB_VISIBLE",
  "BROWSER_FOCUS_LOST",
  "BROWSER_FOCUS_RETURNED",
  "FULLSCREEN_EXITED",
  "FULLSCREEN_ENTERED",
  "FOREGROUND_APP_CHANGED",
  "AGENT_HEARTBEAT",
  "AGENT_DISCONNECTED",
  "EXTENSION_HEARTBEAT",
  "EXTENSION_DISCONNECTED",
  "NETWORK_RECONNECTED",
] as const;

export type ExamEventType = (typeof EXAM_EVENT_TYPES)[number];

export const EVENT_SOURCES = ["extension", "windows-agent", "server"] as const;

export type EventSource = (typeof EVENT_SOURCES)[number];

export type EventMetadata = Record<string, string | number | boolean | null>;

export interface ExamEvent {
  /** UUID generated by the client; the idempotency key for retries. */
  event_id: string;
  contest_id: string;
  session_id: string;
  type: ExamEventType;
  /** ISO-8601 UTC timestamp. */
  occurred_at: string;
  source: EventSource;
  /** Never put passwords, tokens, browsing history, or source code here. */
  metadata?: EventMetadata;
}
